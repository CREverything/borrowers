-- Marketplace listings. Safe to run more than once.
create table if not exists items (
  id integer generated by default as identity primary key,
  title text not null check (length(title) between 1 and 120),
  description text not null default '',
  category text not null check (
    category in ('textbooks', 'study', 'tech', 'dorm', 'kitchen', 'clothing', 'events', 'rec')
  ),
  condition text not null check (condition in ('Like new', 'Good', 'Fair')),
  -- References the lender's user id. Becomes a foreign key once a users table exists.
  lender_id text not null,
  -- Approximate campus spot, never an exact address.
  location text not null,
  switchies_per_day integer not null check (switchies_per_day > 0),
  rating_average numeric(2, 1) check (rating_average between 0 and 5),
  rating_count integer not null default 0 check (rating_count >= 0),
  icon_key text not null,
  keywords text[] not null default '{}',
  max_borrow_days integer not null check (max_borrow_days > 0),
  -- Inclusive date ranges the item is already lent out: [{"start": "YYYY-MM-DD", "end": "YYYY-MM-DD"}]
  booked_ranges jsonb not null default '[]'::jsonb check (jsonb_typeof(booked_ranges) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists items_category_idx on items (category);
