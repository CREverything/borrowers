-- Borrowers schema. Safe to run more than once, on a fresh database or an
-- existing one. Run through `npm run db:migrate` (or db:seed), which also adds
-- demo lender profiles and then applies constraints.sql.

-- Marketplace profiles, keyed by Clerk's user id. No passwords or tokens are
-- stored here; Clerk manages credentials and sessions.
create table if not exists users (
  clerk_id text primary key,
  display_name text not null default '',
  avatar_url text,
  created_at timestamptz not null default now()
);

-- Marketplace listings.
create table if not exists items (
  id integer generated by default as identity primary key,
  title text not null check (length(title) between 1 and 120),
  description text not null default '',
  category text not null check (
    category in ('textbooks', 'study', 'tech', 'dorm', 'kitchen', 'clothing', 'events', 'rec')
  ),
  condition text not null check (condition in ('Like new', 'Good', 'Fair')),
  -- The lender's users.clerk_id (foreign key added in constraints.sql).
  lender_id text not null,
  -- Approximate campus spot, never an exact address.
  location text not null,
  switchies_per_day integer not null check (switchies_per_day > 0),
  rating_average numeric(2, 1) check (rating_average between 0 and 5),
  rating_count integer not null default 0 check (rating_count >= 0),
  icon_key text not null,
  keywords text[] not null default '{}',
  max_borrow_days integer not null check (max_borrow_days > 0),
  -- Inclusive date ranges the item is already lent out: [{"start": "YYYY-MM-DD", "end": "YYYY-MM-DD"}]
  -- Kept for the current availability display until reservations exist.
  booked_ranges jsonb not null default '[]'::jsonb check (jsonb_typeof(booked_ranges) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Columns added after the first release. CREATE TABLE IF NOT EXISTS leaves an
-- existing table unchanged, so they are added separately.
-- Photo uploads aren't wired up yet; this will hold a hosted image URL, never image bytes.
alter table items add column if not exists image_url text;
-- active: shown in the marketplace. hidden: only the owner sees it.
-- removed: soft-deleted, kept for history.
alter table items add column if not exists status text not null default 'active';

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'items_status_check' and conrelid = 'items'::regclass
  ) then
    alter table items add constraint items_status_check
      check (status in ('active', 'hidden', 'removed'));
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'items_image_url_check' and conrelid = 'items'::regclass
  ) then
    alter table items add constraint items_image_url_check
      check (image_url is null or image_url ~ '^https://');
  end if;
end $$;

create index if not exists items_category_idx on items (category);
create index if not exists items_lender_id_idx on items (lender_id);

-- Switchies balance. Every account starts with 5; the database refuses to
-- let it go below zero, so an approval can never overdraw a borrower.
alter table users add column if not exists switchies_balance integer not null default 5;
-- The line above does nothing once the column exists, so set the default
-- explicitly too. Only affects accounts created afterwards.
alter table users alter column switchies_balance set default 5;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'users_switchies_balance_check' and conrelid = 'users'::regclass
  ) then
    alter table users add constraint users_switchies_balance_check check (switchies_balance >= 0);
  end if;
end $$;

-- Several items requested together for one event. Each item still gets its
-- own borrow request, because each lender approves separately.
create table if not exists event_requests (
  id bigint generated always as identity primary key,
  borrower_id text not null references users (clerk_id),
  event_title text not null check (length(event_title) between 1 and 120),
  description text not null default '' check (length(description) <= 500),
  start_date date not null,
  end_date date not null check (end_date >= start_date),
  status text not null default 'pending' check (status in ('pending', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- A request to borrow one item for a date range. lender_id, price and total
-- are copied in when the request is made, so later listing edits don't change it.
create table if not exists borrow_requests (
  id bigint generated always as identity primary key,
  item_id integer not null references items (id),
  borrower_id text not null references users (clerk_id),
  lender_id text not null references users (clerk_id),
  start_date date not null,
  end_date date not null check (end_date >= start_date),
  days integer not null check (days > 0),
  switchies_per_day integer not null check (switchies_per_day > 0),
  total_switchies integer not null check (total_switchies >= 0),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'declined', 'cancelled')),
  event_request_id bigint references event_requests (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (borrower_id <> lender_id)
);

create index if not exists borrow_requests_borrower_idx on borrow_requests (borrower_id);
create index if not exists borrow_requests_lender_idx on borrow_requests (lender_id);
create index if not exists borrow_requests_item_idx on borrow_requests (item_id, status);
create index if not exists event_requests_borrower_idx on event_requests (borrower_id);

-- Request lifecycle: when the lender decided, when they want it back, and
-- when they confirmed it came back. An early return is fine.
alter table borrow_requests add column if not exists decided_at timestamptz;
alter table borrow_requests add column if not exists return_due_at timestamptz;
alter table borrow_requests add column if not exists returned_at timestamptz;
-- The lender's score for the borrower, given when (or after) marking it returned.
alter table borrow_requests add column if not exists borrower_rating smallint;
alter table borrow_requests add column if not exists borrower_rating_comment text;

do $$
begin
  -- Allow the 'returned' status. Recreated by name, so this is safe to rerun.
  alter table borrow_requests drop constraint if exists borrow_requests_status_check;
  alter table borrow_requests add constraint borrow_requests_status_check
    check (status in ('pending', 'approved', 'declined', 'cancelled', 'returned'));

  if not exists (
    select 1 from pg_constraint
    where conname = 'borrow_requests_borrower_rating_check' and conrelid = 'borrow_requests'::regclass
  ) then
    alter table borrow_requests add constraint borrow_requests_borrower_rating_check
      check (borrower_rating between 1 and 5
             and (borrower_rating_comment is null or length(borrower_rating_comment) <= 500));
  end if;
end $$;

-- A borrower's review of a listing. One per borrower per listing, only after
-- a request for it was returned (checked by the API).
create table if not exists reviews (
  id bigint generated always as identity primary key,
  item_id integer not null references items (id),
  borrower_id text not null references users (clerk_id),
  request_id bigint not null references borrow_requests (id),
  rating smallint not null check (rating between 1 and 5),
  comment text not null default '' check (length(comment) <= 1000),
  created_at timestamptz not null default now(),
  unique (item_id, borrower_id)
);

create index if not exists reviews_item_idx on reviews (item_id, created_at desc);

-- In-app notifications. `data` holds the facts (names, dates, times) so the
-- browser can phrase them and show times in the reader's own time zone.
create table if not exists notifications (
  id bigint generated always as identity primary key,
  user_id text not null references users (clerk_id),
  kind text not null,
  role text not null check (role in ('borrower', 'lender')),
  data jsonb not null default '{}'::jsonb,
  request_id bigint references borrow_requests (id),
  item_id integer references items (id),
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists notifications_user_idx on notifications (user_id, created_at desc);

-- Loan tracking. `approved` stays the stored status for a booked loan; these
-- timestamps say where it is, and the API derives a stage from them:
--   approved, no handover            -> upcoming
--   approved, handed over            -> active
--   approved, borrower says returned -> return pending (lender must confirm)
alter table borrow_requests add column if not exists handed_over_at timestamptz;
alter table borrow_requests add column if not exists return_requested_at timestamptz;

-- A borrower's request for more time on an active loan. Nothing changes on
-- the loan until the lender approves; then the deadline, end date and price
-- move together, in one transaction with the extra Switchies.
create table if not exists extension_requests (
  id bigint generated always as identity primary key,
  request_id bigint not null references borrow_requests (id),
  borrower_id text not null references users (clerk_id),
  lender_id text not null references users (clerk_id),
  current_due_at timestamptz not null,
  requested_due_at timestamptz not null check (requested_due_at > current_due_at),
  new_end_date date not null,
  extra_days integer not null check (extra_days >= 0),
  extra_switchies integer not null check (extra_switchies >= 0),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'declined', 'cancelled')),
  created_at timestamptz not null default now(),
  decided_at timestamptz
);

-- At most one open extension per loan.
create unique index if not exists extension_requests_one_pending
  on extension_requests (request_id) where status = 'pending';
create index if not exists extension_requests_lender_idx on extension_requests (lender_id, status);

-- Deadline reminders are sent at most once per person, loan, kind and
-- deadline. A changed deadline (extension, new return time) gets fresh ones.
create unique index if not exists notifications_deadline_once
  on notifications (user_id, request_id, kind, (data->>'returnDueAt'))
  where kind in ('due_in_72h', 'due_in_24h', 'overdue', 'loan_overdue');

-- Late returns cost 5 Switchies per full hour past the deadline, charged when
-- the lender confirms the return and paid to the lender. This records what
-- was actually charged (capped at the borrower's balance, which can't go
-- below zero).
alter table borrow_requests add column if not exists late_fee_switchies integer
  check (late_fee_switchies is null or late_fee_switchies >= 0);

-- Listing photos, stored in the database (there's no separate file storage).
-- The browser shrinks them before upload; the API checks type and size.
-- Lowest position is the cover photo.
create table if not exists item_images (
  id bigint generated always as identity primary key,
  item_id integer not null references items (id),
  position integer not null default 0,
  content_type text not null check (content_type in ('image/jpeg', 'image/png', 'image/webp')),
  data bytea not null check (octet_length(data) between 1 and 2097152),
  created_at timestamptz not null default now()
);

create index if not exists item_images_item_idx on item_images (item_id, position, id);

-- A user's saved listings.
create table if not exists favourites (
  user_id text not null references users (clerk_id),
  item_id integer not null references items (id),
  created_at timestamptz not null default now(),
  primary key (user_id, item_id)
);

-- The borrower's preferred return time, e.g. from an event plan. The lender
-- still sets the actual deadline when approving; this is the suggested default.
alter table borrow_requests add column if not exists requested_return_at timestamptz;

-- Saved event plans. Requirements (what's needed, how many, which listings
-- are picked) are plan content, kept as validated JSON. Borrow requests made
-- from a plan are real borrow_requests rows, linked below; their status is
-- always read from borrow_requests, never copied.
create table if not exists event_plans (
  id bigint generated always as identity primary key,
  owner_id text not null references users (clerk_id),
  title text not null check (length(title) between 1 and 120),
  description text not null default '' check (length(description) <= 1000),
  prompt text not null default '' check (length(prompt) <= 500),
  event_date date,
  start_at timestamptz,
  return_at timestamptz,
  -- The owner's local calendar dates for start_at and return_at; requests are booked by date.
  start_date date,
  end_date date,
  requirements jsonb not null default '[]'::jsonb check (jsonb_typeof(requirements) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (start_at is null or return_at is null or return_at > start_at),
  check (start_date is null or end_date is null or end_date >= start_date)
);

create index if not exists event_plans_owner_idx on event_plans (owner_id, updated_at desc);

create table if not exists event_plan_requests (
  plan_id bigint not null references event_plans (id) on delete cascade,
  request_id bigint not null unique references borrow_requests (id),
  requirement_key text not null,
  item_id integer not null references items (id),
  created_at timestamptz not null default now(),
  primary key (plan_id, request_id)
);
